<section class="policy-section" id="como-funciona" aria-labelledby="funciona-title">
    <div><p class="eyebrow">01 · El recorrido</p><h2 id="funciona-title">Cómo funciona la tienda</h2></div>
    <div>
        <ol class="policy-steps">
            <li><strong>Explora y elige.</strong> Consulta el catálogo, abre un modelo y añade una talla disponible al carrito.</li>
            <li><strong>Prepara tu pedido ficticio.</strong> Revisa las cantidades y completa el formulario con un nombre, una dirección y un correo inventados, por ejemplo <code>persona@example.test</code>.</li>
            <li><strong>Simula el pago.</strong> Usa exclusivamente los datos de tarjeta de prueba que aparecen en la pantalla de pago. Nunca introduzcas una tarjeta real.</li>
            <li><strong>Comprueba el resultado.</strong> Consulta el estado y la factura de demostración desde la página del pedido. El back-office permite practicar su gestión y la atención de incidencias.</li>
        </ol>
        <p>Crear un pedido registra datos y eventos de prueba. No formaliza una compra ni genera una obligación de entrega.</p>
    </div>
</section>

<section class="policy-section" id="pagos-envios" aria-labelledby="pagos-title">
    <div><p class="eyebrow">02 · Sin cobros ni entregas</p><h2 id="pagos-title">Pagos y envíos simulados</h2></div>
    <div>
        <p>No existe una pasarela de pago conectada ni se realiza ningún cargo. Los importes, descuentos, impuestos y gastos de envío son cálculos del ejercicio.</p>
        <p>Los estados «Pendiente de preparación» y «Enviado» representan pasos de una demostración. No se prepara ningún paquete, no interviene un transportista y no hay plazos de entrega reales.</p>
        <p>La factura generada es un documento de prueba sin validez comercial o fiscal.</p>
    </div>
</section>

<section class="policy-section" id="cambios-devoluciones" aria-labelledby="cambios-title">
    <div><p class="eyebrow">03 · Atención de prueba</p><h2 id="cambios-title">Cambios, devoluciones y cancelaciones</h2></div>
    <div>
        <p>Puedes enviar una consulta ficticia de cambio de talla, devolución o incidencia desde la página de tu pedido. Se registra como solicitud de soporte para probar el seguimiento.</p>
        <p>El equipo puede revisar la solicitud y modificar estados de prueba. No hay recogidas, cambios físicos ni reembolsos: no se han entregado productos ni cobrado dinero.</p>
    </div>
</section>

<section class="policy-section" id="datos" aria-labelledby="datos-title">
    <div><p class="eyebrow">04 · Usa datos ficticios</p><h2 id="datos-title">Datos de prueba y cookies</h2></div>
    <div>
        <p>Introduce únicamente información inventada. No uses tu dirección, contraseñas de otras cuentas, tarjetas ni información sensible. La aplicación guarda los datos introducidos, pedidos, consultas y eventos para ejecutar y evaluar la práctica.</p>
        <p>Se utiliza una cookie de sesión para mantener el carrito, el acceso a la cuenta y la protección de los formularios. El código de esta tienda no incorpora publicidad ni herramientas externas de seguimiento.</p>
        <p>Según la configuración de la demostración, se pueden generar correos y avisos externos. Si conectas Telegram, se almacena el identificador del chat asociado a tu cliente de prueba; ese identificador puede ser personal, aunque el pedido sea ficticio.</p>
        <p>Si está habilitado el asistente de IA externo, el flujo puede enviar datos del pedido y de la consulta al proveedor configurado para preparar una propuesta. Evita cualquier dato personal o sensible también en los mensajes de soporte.</p>
        <p>Si introduces información real por error, avisa al equipo responsable de la práctica para que revise y retire los registros afectados. Estas indicaciones describen el prototipo; su uso comercial requeriría una revisión específica.</p>
    </div>
</section>

<section class="policy-section" id="soporte" aria-labelledby="soporte-title">
    <div><p class="eyebrow">05 · Con revisión humana</p><h2 id="soporte-title">Ayuda y avisos por Telegram</h2></div>
    <div>
        <p>Abre tu pedido y utiliza su formulario de soporte para crear una consulta de prueba. Guarda el acceso al pedido y no compartas su enlace ni los enlaces de vinculación.</p>
        <p>Si el bot está configurado, el botón «Recibir avisos por Telegram» genera un enlace de un solo uso que caduca a los 30 minutos. El código del pedido por sí solo no permite vincular el chat.</p>
        <p>Los avisos de Telegram pueden llegar de verdad al chat conectado. Las propuestas del asistente quedan pendientes de revisión y el envío de su respuesta requiere aprobación humana en el back-office. No existe un compromiso de atención ni un horario de soporte comercial.</p>
    </div>
</section>

